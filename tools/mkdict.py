"""mkdict — builds src/dict_en.c, the small English word list used by the
word-spacing fix (src/words.c), from SCOWL (http://wordlist.aspell.net/).

usage: python3 tools/mkdict.py SCOWL_DIR/final > src/dict_en.c
       python3 tools/mkdict.py SCOWL_DIR/final --bin radio/SKIMDICT.BIN

It takes SCOWL size 10 (the most common English words: english, american and
british lists), letters a-z only, two letters or more, in capitals.

Format (compact, no pointers, freestanding C):
  - words are grouped by their first two letters (26 x 26 buckets);
  - dict_idx[b] is the byte offset of bucket b in dict_data, dict_idx[676]
    is the end;
  - inside a bucket each word is stored without its first two letters, front
    coded against the previous one: a header byte (high nibble = letters kept
    from the previous word, low nibble = new letters) and the new letters.

SKIMDICT.BIN (--bin), read by the radio app: "SKD1", the 677 offsets as
little-endian 16-bit numbers, then the data.
"""
import re
import sys

LEVEL = 10


def load(final):
    words = set()
    for name in ("english-words", "american-words", "british-words"):
        try:
            with open(f"{final}/{name}.{LEVEL}", encoding="latin-1") as f:
                data = f.read().split()
        except FileNotFoundError:
            continue
        for w in data:
            if re.fullmatch(r"[a-z]{2,}", w):
                words.add(w.upper())
    return sorted(words)


def main():
    if len(sys.argv) not in (2, 4) or (len(sys.argv) == 4 and sys.argv[2] != "--bin"):
        sys.exit(__doc__)
    words = load(sys.argv[1])
    buckets = [[] for _ in range(26 * 26)]
    for w in words:
        buckets[(ord(w[0]) - 65) * 26 + ord(w[1]) - 65].append(w[2:])
    data = bytearray()
    idx = []
    for b in buckets:
        idx.append(len(data))
        prev = ""
        for rest in b:
            p = 0
            while p < len(prev) and p < len(rest) and prev[p] == rest[p] and p < 15:
                p += 1
            new = rest[p:]
            if len(new) > 15:
                sys.exit(f"word too long: {rest}")
            data.append((p << 4) | len(new))
            data += new.encode("ascii")
            prev = rest
    idx.append(len(data))

    if len(sys.argv) == 4:
        with open(sys.argv[3], "wb") as f:
            f.write(b"SKD1")
            for v in idx:
                f.write(v.to_bytes(2, "little"))
            f.write(data)
        return

    out = sys.stdout
    out.write("/* Generated by tools/mkdict.py from SCOWL size %d - do not edit.\n" % LEVEL)
    out.write(" * %d words, %d bytes.\n *\n" % (len(words), len(data) + 2 * len(idx)))
    out.write(" * Word list from SCOWL (Spell Checker Oriented Word Lists),\n")
    out.write(" * Copyright 2000-2018 by Kevin Atkinson. See THIRD_PARTY_NOTICES.md for\n")
    out.write(" * the full copyright and permission notice. */\n")
    out.write('#include "dict_en.h"\n\n')
    out.write("const unsigned short dict_idx[677] = {\n")
    for i in range(0, len(idx), 12):
        out.write("    " + ", ".join(str(v) for v in idx[i:i + 12]) + ",\n")
    out.write("};\n\n")
    out.write("const unsigned char dict_data[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join(str(v) for v in data[i:i + 16]) + ",\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
